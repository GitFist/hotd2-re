"""Prepare the supplied PC edition's word data; never needed by the game at runtime.

Usage: python tools/import_typing_words.py <reference-directory>
Only data records and their order are imported. No executable code is imported.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import unicodedata


GROUP_STARTS = (0, 20, 24, 34, 132, 133, 134, 321, 409, 484, 486, 488)
BUILTINS = (("KEYS", 0x58A270, 26), ("SHORT", 0x58A3A8, 41),
            ("STAFF_A", 0x58A598, 21), ("STAFF_B", 0x58A698, 27),
            ("ABBREVIATIONS", 0x58A7E0, 60), ("HOME_KEYS", 0x58A058, 2),
            ("NUMBER_KEYS", 0x58A070, 9), ("ZERO_KEY", 0x58A0E0, 1),
            ("SYMBOL_KEYS", 0x58A0EC, 9))


def c_string(data: bytes) -> str:
    return '"' + ''.join(chr(b) if 32 <= b <= 126 and b not in (34, 92)
                         else '\\"' if b == 34 else '\\\\' if b == 92
                         else f'\\{b:03o}' for b in data) + '"'


def zero_string(data: bytes, offset: int) -> bytes:
    if not 0 <= offset < len(data):
        raise ValueError(f"string offset out of bounds: {offset}")
    end = data.find(b"\0", offset)
    if end < 0:
        raise ValueError("unterminated string")
    return data[offset:end]


def prepare(reference: Path, output: Path) -> None:
    # The PE supplies resource names and built-in text records, not program code.
    import pefile
    pe = pefile.PE(str(reference / "Tod_e.exe"))
    memory = pe.get_memory_mapped_image()
    base = pe.OPTIONAL_HEADER.ImageBase
    def read_va(address: int) -> bytes:
        return zero_string(memory, address - base)
    names = [read_va(struct.unpack_from("<I", memory, 0x4F0B78-base+i*4)[0]).decode("ascii")
             for i in range(488)]
    if len(set(names)) != 488:
        raise ValueError("unexpected reference word catalog")
    if set(names) != {p.name for p in (reference / "word").glob("Z*.bin")}:
        raise ValueError("word files do not match the reference catalog")

    glyph_map: dict[int, int] = {}
    records = []
    banks = []
    digest = hashlib.sha256()
    def add_record(metadata: int, text: bytes, glyphs: bytes) -> None:
        stripped = glyphs.replace(b"\xff", b"")
        if len(text) != len(stripped) or any(c < 32 or c > 126 for c in text):
            raise ValueError("unsupported word encoding")
        for glyph, character in zip(stripped, text):
            if glyph in glyph_map and glyph_map[glyph] != character:
                raise ValueError("ambiguous glyph encoding")
            glyph_map[glyph] = character
        digest.update(struct.pack("<I", metadata) + text + b"\0" + glyphs + b"\0")
        records.append((metadata & 0xffff, metadata >> 16, text, glyphs))

    for index, name in enumerate(names):
        data = bytes(b ^ 0x41 for b in (reference / "word" / name).read_bytes())
        first = len(records)
        for offset in range(0, len(data)-11, 12):
            metadata, text_offset, glyph_offset = struct.unpack_from("<III", data, offset)
            if metadata == 0xffffffff:
                break
            add_record(metadata, zero_string(data, text_offset), zero_string(data, glyph_offset))
        else:
            raise ValueError(f"missing record sentinel in {name}")
        group = next(g for g in range(11) if GROUP_STARTS[g] <= index < GROUP_STARTS[g+1])
        banks.append((name[:-4], group, index-GROUP_STARTS[group]+1, first, len(records)-first))
    if len(records) != 14061:
        raise ValueError(f"unexpected record count: {len(records)}")

    builtins = []
    for name, address, count in BUILTINS:
        first = len(records)
        for i in range(count):
            metadata, text_va, glyph_va = struct.unpack_from("<III", memory, address-base+i*12)
            text = read_va(text_va)
            if any(byte > 127 for byte in text):
                # Original home-row/numeric labels use fullwidth Shift-JIS
                # Latin glyphs. Their typing glyphs still encode ASCII keys.
                text = unicodedata.normalize("NFKC",text.decode("cp932")).encode("ascii")
            add_record(metadata, text, read_va(glyph_va))
        builtins.append((name, first, count))

    lines = ["// Generated by tools/import_typing_words.py. Original data order is significant.",
             f'// Canonical record SHA-256: {digest.hexdigest()}',
             "constexpr TypingWordRecord kWords[] = {"]
    lines += [f"    {{{metric}, {flags}, {c_string(text)}, {c_string(glyphs)}}},"
              for metric, flags, text, glyphs in records]
    lines += ["};", "constexpr TypingWordBank kBanks[] = {"]
    lines += [f'    {{"{name}", {group}, {level}, {first}, {count}}},'
              for name, group, level, first, count in banks]
    lines += ["};", "constexpr TypingBuiltinBank kBuiltinBanks[] = {"]
    lines += [f'    {{"{name}", {first}, {count}}},' for name, first, count in builtins]
    lines += ["};", ""]
    for label, address, count in (("Early",0x589F18,35),("Late",0x589FA8,41)):
        levels = struct.unpack_from("<"+"I"*count,memory,address-base)
        if not all(1 <= level <= 88 for level in levels):
            raise ValueError("invalid bonus-bank selector table")
        lines += [f"constexpr uint32_t kBonusBanks{label}[] = {{"+", ".join(map(str,levels))+"};", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(json.dumps({"banks": len(banks), "fileRecords": 14061,
                      "builtinRecords": len(records)-14061, "sha256": digest.hexdigest()}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1]/"src/game/typing_word_data.inc")
    args = parser.parse_args()
    prepare(args.reference, args.output)
