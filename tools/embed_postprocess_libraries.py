"""Embed pinned, licensed shader sources for an extract-and-play executable.

Upstream files remain unchanged beside their license/provenance manifests. Only
SMAA sampler declarations gain explicit runtime register bindings in the copy.
Separate small literals also support MSVC's individual string-literal limit.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1] / "src/port/render/third_party"

def compact(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return "\n".join(line.strip() for line in text.splitlines() if line.strip()) + "\n"

def embed(name, text):
    chunks = [text[i:i+8000] for i in range(0,len(text),8000)]
    assert all(")H2SHADER\"" not in chunk for chunk in chunks)
    return "inline const char* const " + name + "[] = {\n" + ",\n".join('R"H2SHADER('+c+')H2SHADER"' for c in chunks) + "\n};\n"

smaa = (ROOT/"smaa/SMAA.hlsl").read_text()
smaa = smaa.replace("SamplerState LinearSampler { Filter = MIN_MAG_LINEAR_MIP_POINT; AddressU = Clamp; AddressV = Clamp; };", "SamplerState LinearSampler : SAMP_REG;")
smaa = smaa.replace("SamplerState PointSampler { Filter = MIN_MAG_MIP_POINT; AddressU = Clamp; AddressV = Clamp; };", "SamplerState PointSampler : POINT_SAMP_REG;")
assert "SamplerState LinearSampler : SAMP_REG;" in smaa
fsr = (ROOT/"fsr1/ffx_a.h").read_text() + "\n" + (ROOT/"fsr1/ffx_fsr1.h").read_text()
output = "// Generated by tools/embed_postprocess_libraries.py; see source licenses and PROVENANCE.json.\n"
output += embed("kSmaaLibraryChunks",compact(smaa))
output += embed("kFsrLibraryChunks",compact(fsr))
(ROOT/"embedded_libraries.inc").write_text(output,newline="\n")
print("Embedded",len(output),"bytes")
