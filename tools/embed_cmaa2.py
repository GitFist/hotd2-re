"""Embed Intel's pinned CMAA2 without changing its distributed upstream file.

SDL's D3D12 buffers expose raw UAV descriptors. Translate the three structured
arrays to equivalent byte-address loads/stores, retaining the original algorithm.
Both backends use this same translation. Source colors use the existing UNORM
scene resource, so decode the one LoadColor() input to match an sRGB SRV.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]/"src/port/render/third_party"
source=(ROOT/"cmaa2/CMAA2.hlsl").read_text()
for name,stride in [("g_workingShapeCandidates",4),("g_workingDeferredBlendLocationList",4),("g_workingDeferredBlendItemList",8)]:
    source,count=re.subn(r"RWStructuredBuffer<uint2?>\s+("+name+r"\s*:)",r"RWByteAddressBuffer \1",source)
    assert count==1,(name,count)
    store="Store2" if stride==8 else "Store"
    source,count=re.subn(name+r"\[([^\]]+)\]\s*=\s*([^;]+);",lambda m:f"{name}.{store}(({m[1]})*{stride}, {m[2]});",source)
    assert count==1,(name,count)
    load="Load2" if stride==8 else "Load"
    source=re.sub(name+r"\[([^\]]+)\]",lambda m:f"{name}.{load}(({m[1]})*{stride})",source)
    source=source.replace(name+".GetDimensions( appendBufferMaxCount, appendBufferStride );",name+f".GetDimensions( appendBufferMaxCount ); appendBufferMaxCount/={stride}; appendBufferStride={stride};")
needle="lpfloat3 color = g_inoutColorReadonly.Load( int3( pixelPos, 0 ), offset ).rgb;"
assert needle in source
source=source.replace(needle,needle+"\ncolor=lerp(pow((color+.055)/1.055,2.4),color/12.92,step(color,.04045));")
source+="\n[numthreads(16,1,1)] void ResetCS(uint3 id:SV_DispatchThreadID){g_workingControlBuffer.Store(id.x*4,0);}\n"
source=re.sub(r"/\*.*?\*/","",source,flags=re.S)
source=re.sub(r"//[^\n]*","",source)
source="\n".join(line.strip() for line in source.splitlines() if line.strip())+"\n"
chunks=[source[i:i+8000] for i in range(0,len(source),8000)]
out="// Generated by tools/embed_cmaa2.py. See upstream source, Apache-2 license and provenance.\ninline const char* const kCmaaLibraryChunks[]={\n"
out+=",\n".join('R"H2CMAA('+chunk+')H2CMAA"' for chunk in chunks)+"\n};\n"
(ROOT/"cmaa2_embedded.inc").write_text(out,newline="\n")
print("Embedded",len(out),"bytes")
